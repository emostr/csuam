const attr = (s: string) =>
  s.replaceAll('&', '&amp;').replaceAll('"', '&quot;').replaceAll('<', '&lt;').replaceAll('>', '&gt;')

const h1 = (t: string) => `<h1>${t}</h1>`
const h2 = (t: string) => `<h2>${t}</h2>`
const h3 = (t: string) => `<h3>${t}</h3>`
const p = (t: string) => `<p>${t}</p>`
const center = (t: string) => `<p style="text-align: center">${t}</p>`
const ul = (items: string[]) => `<ul>${items.map((i) => `<li><p>${i}</p></li>`).join('')}</ul>`
const ol = (items: string[]) => `<ol>${items.map((i) => `<li><p>${i}</p></li>`).join('')}</ol>`
const quote = (t: string) => `<blockquote><p>${t}</p></blockquote>`
const tasks = (items: string[]) =>
  `<ul data-type="taskList">${items
    .map((i) => `<li data-type="taskItem" data-checked="false"><p>${i}</p></li>`)
    .join('')}</ul>`
const facts = (rows: [string, string][]) =>
  `<table><tbody>${rows.map(([k, v]) => `<tr><th><p>${k}</p></th><td><p>${v}</p></td></tr>`).join('')}</tbody></table>`
const grid = (head: string[], rows: string[][]) =>
  `<table><tbody><tr>${head.map((h) => `<th><p>${h}</p></th>`).join('')}</tr>${rows
    .map((r) => `<tr>${r.map((c) => `<td><p>${c}</p></td>`).join('')}</tr>`)
    .join('')}</tbody></table>`
const m = (latex: string) => `<span data-type="inline-math" data-latex="${attr(latex)}"></span>`
const mb = (latex: string) => `<div data-type="block-math" data-latex="${attr(latex)}"></div>`

